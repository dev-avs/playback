// Generates scripts/snapshot/scenes.settings.mjs: one scene per non-default value of
// each appearance setting, derived from DEFAULTS (src/settings.ts) and the
// toggle()/slider()/chips() items in src/windows/Settings.tsx (read with the TS compiler):
//   toggle → the flipped value;  chips → every other option;  slider → the end of its
//   range farthest from the default.
//   node scripts/snapshot/gen-scenes.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");
const { DEFAULTS, HIGHLIGHTS, GLASS_TINTS, LYRIC_FONTS } = require("./settings-meta.cjs")();
const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(HERE, "..", "..", "src", "windows", "Settings.tsx"), "utf8");
const sf = ts.createSourceFile("Settings.tsx", src, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TSX);

// Settings that change no pixels of a captured widget (behaviour, other windows, per-language
// faces the English fixture never uses), or are covered by a core scene or a motion.
const SKIP = new Set([
  "alwaysOnTop", "lyricsOnLaunch", "hideWhenIdle", "showChangelog", "clickToJump", "scrollSpeed", "autoSync",
  "followSpeed", "lyricOffset", "lyricProvider", "albumOnLaunch", "romanizeDefault", "fontJa", "fontKo", "fontZh",
  "fsOnTop", "animationStyle", "lyricMotion", "panSpeed", "rainbowSpeed", "spinSpeed", "lyricFont",
]);

const num = (n) => Function(`return (${n.getText(sf)})`)();
const str = (n) => (n && ts.isStringLiteralLike(n) ? n.text : undefined);
const found = [];
(function walk(n) {
  if (ts.isCallExpression(n) && ts.isIdentifier(n.expression) && ["toggle", "slider", "chips"].includes(n.expression.text)) {
    const kind = n.expression.text;
    const [cat, key] = [str(n.arguments[0]), str(n.arguments[1])];
    if (cat && key) {
      const item = { kind, cat, key };
      if (kind === "slider") {
        const o = n.arguments[4];
        for (const p of o.properties) if (["min", "max", "step"].includes(p.name.text)) item[p.name.text] = num(p.initializer);
      }
      if (kind === "chips") {
        const arr = n.arguments[4];
        if (arr && ts.isArrayLiteralExpression(arr))
          item.values = arr.elements.map((e) => e.properties.find((p) => p.name?.text === "value")?.initializer).map(str);
        else if (key === "highlight") item.values = Object.keys(HIGHLIGHTS);
        else if (key === "glassTint") item.values = Object.keys(GLASS_TINTS);
      }
      found.push(item);
    }
  }
  ts.forEachChild(n, walk);
})(sf);

const PLAYING = { state: { playing: true, status: "Playing" } };
const NEXT = { responses: { getNext: { id: "n1", name: "Next Song", artist: "Next Artist", image: null } } };
// 4000 ms: past the 2500 ms the fullscreen controls wait before fading (App.tsx FS_IDLE_MS), so the
// outcome does not hang on when a resize-triggered mousemove woke them
const FS = { size: [1280, 720], steps: [{ op: "emit", event: "fullscreen" }, { op: "wait", ms: 4000 }] };
const HOVER = [{ op: "move", selector: ".widget" }, { op: "wait", ms: 600 }];

function base(cat, key) {
  const lyrics = { lyricsOnLaunch: true };
  if (cat === "fullscreen") return { settings: {}, ...FS };
  if (cat === "album") return { settings: { ...lyrics, albumOnLaunch: true } };
  if (cat === "fun") return { settings: lyrics, fake: PLAYING };
  if (cat === "controls" && key !== "pinControls") return { settings: lyrics, steps: HOVER };
  if (key === "nextSong") return { settings: {}, fake: NEXT };
  return { settings: lyrics };
}

const scenes = [];
const add = (cat, key, value, label) => {
  const b = base(cat, key);
  const s = { name: `set-${key}${label ? "-" + label : ""}`, kind: "setting", window: "widget", ...b, settings: { ...b.settings, [key]: value } };
  if (key === "nextSong" && value !== "off") s.fake = { ...NEXT, state: { playing: true, status: "Playing", position: 191 } };
  scenes.push(s);
};
for (const it of found) {
  if (SKIP.has(it.key) || !(it.key in DEFAULTS)) continue;
  const d = DEFAULTS[it.key];
  if (it.kind === "toggle") add(it.cat, it.key, !d);
  else if (it.kind === "chips") {
    for (const v of it.values ?? []) if (v !== d) add(it.cat, it.key, v, v);
  } else {
    const far = Math.abs(it.min - d) >= Math.abs(it.max - d) ? it.min : it.max;
    add(it.cat, it.key, far);
  }
}
for (const f of Object.keys(LYRIC_FONTS)) if (f !== DEFAULTS.lyricFont) add("text", "lyricFont", f, f.toLowerCase().replace(/\s+/g, "-"));

const body = JSON.stringify(scenes, null, 1).replace(/"([A-Za-z_]\w*)":/g, "$1:");
fs.writeFileSync(
  path.join(HERE, "scenes.settings.mjs"),
  `// GENERATED by scripts/snapshot/gen-scenes.mjs from src/settings.ts and src/windows/Settings.tsx. Do not edit.\n// One scene per non-default value of each appearance setting (see that file for the rules).\nexport const scenes = ${body};\n`,
);
console.log(`${scenes.length} setting scenes`);
