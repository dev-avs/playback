"""Export the uroman tables that src/uroman.ts needs into src/vendor/uroman-data.ts.

uroman (https://github.com/isi-nlp/uroman, Ulf Hermjakob, USC ISI) is Python; the
widget needs it in the renderer, so src/uroman.ts ports its romanizer and this
script dumps the data it runs on, read through uroman's own loader so every
overwrite and generated rule (e.g. Thai cancellation) comes out as uroman sees it.

    git clone --depth 1 https://github.com/isi-nlp/uroman <dir>
    python scripts/uroman-data.py <dir>        (needs: pip install regex)

Left out, because the app handles them itself or they never show up in lyrics:
Latin (it is already Latin), Han / kana / hangul (src/romanize.ts), Braille, and
everything outside the Basic Multilingual Plane (historic scripts).
"""
import json
import subprocess
import sys
import unicodedata as ud
from pathlib import Path

import regex

src = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(src))
from uroman.uroman import Uroman  # noqa: E402

u = Uroman()

SKIP = regex.compile(r'[\p{Script=Latin}\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}'
                     r'\p{Script=Hangul}\p{Script=Braille}\U00010000-\U0010FFFF]')

rules = {}
for s, rs in u.rom_rules.items():
    if not s or SKIP.search(s):
        continue
    out = []
    for r in rs:
        if r['t'] is None:
            continue
        flags = ((1 if r['use-only-at-start-of-word'] else 0)
                 | (2 if r['dont-use-at-start-of-word'] else 0)
                 | (4 if r['use-only-at-end-of-word'] else 0)
                 | (8 if r['dont-use-at-end-of-word'] else 0)
                 | (16 if r['use-only-for-whole-word'] else 0))
        entry = [r['t'], flags]
        if r['lcodes'] or r['t-at-end-of-syllable'] is not None:
            entry.append(r['lcodes'] or [])
        if r['t-at-end-of-syllable'] is not None:
            entry.append(r['t-at-end-of-syllable'])
        out.append(entry)
    if out:
        rules[s] = out

abugida = {}
for script in u.scripts.values():
    if script['abugida-default-vowels'] and script['script-name'] != 'Tibetan':
        abugida[script['script-name']] = script['abugida-default-vowels']

# Script names are only consulted for abugidas and Thai.
wanted = set(abugida) | {'Thai'}
scripts = {}
chars = {k[1] for k in u.dict_str if k[0] == 'script'}
for c in sorted(chars):
    name = u.dict_str[('script', c)]
    if name in wanted and ord(c) < 0x10000:
        scripts[name] = scripts.get(name, '') + c


def char_set(key):
    return ''.join(sorted(k[1] for k, v in u.dict_bool.items()
                          if k[0] == key and v and len(k[1]) == 1 and ord(k[1]) < 0x10000))


def named(word):
    return ''.join(c for c in map(chr, range(0x80, 0x10000)) if word in u.chr_name(c))


# Number parsing is not ported, but digits in other scripts (८४ → 84) still map.
digits = [''] * 10
for cp in range(0x80, 0x10000):
    if ud.category(chr(cp)) == 'Nd':
        digits[ud.digit(chr(cp))] += chr(cp)

data = {
    'digits': digits,
    'rules': rules,
    'abugida': abugida,
    'scripts': scripts,
    'vowelSign': char_set('is-vowel-sign'),
    'medial': char_set('is-medial-consonant-sign'),
    'virama': char_set('is-virama'),
    'toneMark': ''.join(sorted(k[1] for k, v in u.dict_str.items() if k[0] == 'tone-mark' and v)),
    'prePost': ''.join(sorted(k[1] for k, v in u.dict_str.items()
                              if k[0] == 'syllable-info' and v == 'written-pre-consonant-spoken-post-consonant')),
    'nukta': named('NUKTA'),
    'subjoined': named('SUBJOINED LETTER'),
    'vocalic': named('VOCALIC'),
}

commit = subprocess.run(['git', '-C', str(src), 'log', '-1', '--format=%h %cs'],
                        capture_output=True, text=True).stdout.strip()
out = Path(__file__).resolve().parent.parent / 'src' / 'vendor' / 'uroman-data.ts'
body = json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
out.write_text(
    '// Generated by scripts/uroman-data.py from uroman ' + commit + ' (https://github.com/isi-nlp/uroman).\n'
    '// "This project uses the universal romanizer software \'uroman\' written by Ulf Hermjakob,\n'
    '// USC Information Sciences Institute (2015-2020)". Licence: src/vendor/uroman-LICENSE.txt.\n'
    '// Do not edit; regenerate.\n'
    'import type { UromanData } from "../uroman";\n\n'
    '// A string parsed once beats a giant object literal for both tsc and startup.\n'
    'export const UROMAN_DATA: UromanData = JSON.parse(' + json.dumps(body, ensure_ascii=False) + ');\n',
    encoding='utf-8', newline='\n')
print(f'{out}: {len(rules)} rules, {out.stat().st_size // 1024} KB')
